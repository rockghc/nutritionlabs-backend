-- Merged NutritionLabs schema.
-- It contains every table of the former microservice databases:
--   NLabsCatalogsBD, NLabsFoodsBD, NLabsRecipesBD, NLabsUserBD and NLabsFileBD.
--
-- Tables renamed because their names collided (or almost collided) after the merge:
--   NLabsUserBD.nlabs_tags             -> nlabs_tags_user
--   NLabsRecipesBD.nlabs_tags          -> nlabs_tags_recipe
--   NLabsFoodsBD.nlabs_common_mesure   -> nlabs_food_common_measures
--   NLabsRecipesBD.nlabs_common_measure -> nlabs_recipe_common_measures
--
-- Run connected to "NutritionLabsBD":
--   psql -h localhost -U postgres -d NutritionLabsBD -f 02_create_schema.sql

CREATE SCHEMA IF NOT EXISTS nutritionlabs AUTHORIZATION postgres;

SET search_path TO nutritionlabs;

-- ============================================================================
-- Catalogs (former NLabsCatalogsBD)
-- ============================================================================

CREATE TABLE nlabs_catalogs (
    id           bigint            NOT NULL,
    name         character varying NOT NULL,
    label        character varying,
    catalog_type character varying,
    CONSTRAINT nlabs_catalogs_pkey PRIMARY KEY (id)
);

CREATE TABLE nlabs_catalog_details (
    id         bigint            NOT NULL,
    id_catalog bigint            NOT NULL,
    name       character varying,
    label      character varying,
    CONSTRAINT nlabs_catalog_details_pkey PRIMARY KEY (id),
    CONSTRAINT nlabs_catalog_fk1 FOREIGN KEY (id_catalog) REFERENCES nlabs_catalogs (id)
);
CREATE INDEX fki_nlabs_catalog_fk1 ON nlabs_catalog_details (id_catalog);

CREATE TABLE nlabs_catalog_link (
    id_catalog      bigint                 NOT NULL,
    id_catalog_link bigint                 NOT NULL,
    link_type       character varying(100) NOT NULL,
    CONSTRAINT nlabs_catalog_link_pkey PRIMARY KEY (id_catalog, id_catalog_link),
    CONSTRAINT nlabs_catalog_link_fk1 FOREIGN KEY (id_catalog) REFERENCES nlabs_catalog_details (id),
    CONSTRAINT nlabs_catalog_link_fk2 FOREIGN KEY (id_catalog_link) REFERENCES nlabs_catalog_details (id)
);
CREATE INDEX fki_nlabs_catalog_link_fk2 ON nlabs_catalog_link (id_catalog_link);

-- ============================================================================
-- Foods (former NLabsFoodsBD)
-- ============================================================================

CREATE TABLE nlabs_catalogs_labels (
    id    bigint            NOT NULL,
    label character varying NOT NULL,
    CONSTRAINT nlabs_catalogs_labels_pkey PRIMARY KEY (id)
);

CREATE TABLE nlabs_groups (
    id   bigint            NOT NULL,
    name character varying NOT NULL,
    CONSTRAINT nlabs_groups_pkey PRIMARY KEY (id)
);

CREATE TABLE nlabs_foods (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    name       character varying NOT NULL,
    food_group bigint,
    quantity   bigint,
    food_type  character varying(10),
    id_source  bigint,
    version    bigint DEFAULT 0,
    CONSTRAINT nlabs_foods_pkey PRIMARY KEY (id),
    CONSTRAINT fk_source_label FOREIGN KEY (id_source) REFERENCES nlabs_catalogs_labels (id)
);
CREATE INDEX idx_nlabs_foods_food_type ON nlabs_foods (food_type);

CREATE TABLE nlabs_foods_nutriments (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    id_food              bigint  NOT NULL,
    id_nutriment_catalog integer NOT NULL,
    quantity             double precision,
    version              bigint DEFAULT 0,
    CONSTRAINT nlabs_foods_nutriments_pkey PRIMARY KEY (id),
    CONSTRAINT nlabs_foods_nutriments_ukey UNIQUE (id_food, id_nutriment_catalog),
    CONSTRAINT nlabs_foods_nutriments_fkey FOREIGN KEY (id_food) REFERENCES nlabs_foods (id)
);

CREATE TABLE nlabs_food_common_measures (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    id_food        bigint NOT NULL,
    singular_name  character varying(100),
    plural_name    character varying(100),
    quantity       double precision,
    total_grams    double precision,
    edible_portion double precision,
    version        bigint DEFAULT 0,
    CONSTRAINT nlabs_food_common_measures_pkey PRIMARY KEY (id),
    CONSTRAINT fk_common_measure_food FOREIGN KEY (id_food) REFERENCES nlabs_foods (id) DEFERRABLE
);
CREATE INDEX idx_nlabs_food_common_measures_food ON nlabs_food_common_measures (id_food);

CREATE TABLE nlabs_foods_users (
    id_food  bigint            NOT NULL,
    username character varying NOT NULL,
    version  bigint DEFAULT 0,
    CONSTRAINT nlabs_foods_users_pkey PRIMARY KEY (id_food, username),
    CONSTRAINT food_user_fk1 FOREIGN KEY (id_food) REFERENCES nlabs_foods (id)
);

