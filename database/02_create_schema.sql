-- id_food keeps a reference to the original food but is intentionally not a foreign key:
-- the ingredient stores a snapshot of the food, so the food may be deleted later.
-- id_common_measure is not a foreign key either, the common measure row is deleted
-- together with the ingredient food and the delete order is managed by Hibernate.
CREATE TABLE nlabs_ingredient_foods (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY,
    name                  character varying,
    real_name             character varying,
    quantity              double precision,
    id_food               bigint,
    id_recipe_ingredients bigint,
    id_common_measure     bigint,
    version               bigint DEFAULT 0,
    CONSTRAINT nlabs_ingredient_foods_pkey PRIMARY KEY (id),
    CONSTRAINT ingredient_food_recipe_fk FOREIGN KEY (id_recipe_ingredients) REFERENCES nlabs_recipe_ingredients (id)
);

CREATE TABLE nlabs_ingredient_foods_common_mesure (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    id_ingredient_food bigint NOT NULL,
    id_external        bigint,
    singular_name      character varying(100),
    plural_name        character varying(100),
    quantity           double precision,
    total_grams        double precision,
    edible_portion     double precision,
    version            bigint DEFAULT 0,
    CONSTRAINT nlabs_ingredient_foods_common_mesure_pkey PRIMARY KEY (id),
    CONSTRAINT fk_ingredient_foods_common_mesure FOREIGN KEY (id_ingredient_food) REFERENCES nlabs_ingredient_foods (id) DEFERRABLE
);

CREATE TABLE nlabs_ingredient_foods_nutriments (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    id_ingredient_food   bigint  NOT NULL,
    id_nutriment_catalog integer NOT NULL,
    quantity             double precision,
    version              bigint DEFAULT 0,
    CONSTRAINT nlabs_ingredient_foods_nutriments_pkey PRIMARY KEY (id),
    CONSTRAINT nlabs_ingredient_foods_nutriments_ukey UNIQUE (id_ingredient_food, id_nutriment_catalog),
    CONSTRAINT nlabs_ingredient_foods_nutriments_fkey FOREIGN KEY (id_ingredient_food) REFERENCES nlabs_ingredient_foods (id)
);

CREATE TABLE nlabs_recipe_nutriments (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
