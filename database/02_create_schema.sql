CREATE TABLE tbl_image (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    created_by   character varying(255),
    created_date timestamp without time zone,
    updated_by   character varying(255),
    updated_date timestamp without time zone,
    status       boolean,
    data         bytea,
    file_name    character varying(255),
    file_type    character varying(255),
    size         bigint,
    system_name  character varying(255),
    uuid         character varying(255),
    type_entity  character varying(500),
    id_entity    bigint,
    property     character varying(300),
    username     character varying,
    CONSTRAINT tbl_image_pkey PRIMARY KEY (id)
);
CREATE INDEX idx_tbl_image_file_name ON tbl_image (file_name);
CREATE INDEX idx_tbl_image_uuid ON tbl_image (uuid);
CREATE INDEX idx_tbl_image_entity ON tbl_image (type_entity, id_entity, property);

CREATE TABLE tbl_image_user (
    id_image integer           NOT NULL,
    username character varying NOT NULL,
    version  bigint DEFAULT 0,
    CONSTRAINT tbl_image_user_pkey PRIMARY KEY (id_image, username),
    CONSTRAINT id_image FOREIGN KEY (id_image) REFERENCES tbl_image (id)
);
