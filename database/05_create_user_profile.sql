-- Profile of the logged account (Keycloak user).
--
-- The row is created together with the Keycloak user (sign up). The profile columns are
-- filled in later by the front interface "complete-profile", so they are nullable.
--
-- It is not related to nlabs_users (patients): the account is identified by its
-- Keycloak username, like nlabs_user_users / nlabs_workplace_users. Keycloak stores the
-- usernames in lower case, so does this table.
--
-- id_gender, id_country and id_profession are ids of nlabs_catalog_details, kept without
-- foreign key like id_gender / id_country_residence of nlabs_users.
--
-- Run connected to "NutritionLabsBD":
--   psql -h localhost -U postgres -d NutritionLabsBD -f 05_create_user_profile.sql

SET search_path TO nutritionlabs;

CREATE TABLE nlabs_user_profiles (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    username      character varying      NOT NULL,
    id_keycloak   character varying(36)  NOT NULL,
    id_gender     bigint,
    id_country    bigint,
    birthdate     date,
    phone_prefix  character varying(5),
    mobile_number character varying(20),
    id_profession bigint,
    creation_date timestamp without time zone NOT NULL DEFAULT now(),
    update_date   timestamp without time zone,
    version       bigint DEFAULT 0,
    CONSTRAINT nlabs_user_profiles_pkey PRIMARY KEY (id),
    CONSTRAINT nlabs_user_profiles_username_ukey UNIQUE (username),
    CONSTRAINT nlabs_user_profiles_id_keycloak_ukey UNIQUE (id_keycloak),
    CONSTRAINT nlabs_user_profiles_phone_prefix_chk CHECK (phone_prefix ~ '^\+[0-9]{1,4}$'),
    CONSTRAINT nlabs_user_profiles_birthdate_chk CHECK (birthdate <= CURRENT_DATE)
);
